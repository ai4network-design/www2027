#!/usr/bin/env python3
"""Present saved capacity and diagnostic summaries; no new statistics or runs.

First import: provide the archived converter-fix Markdown with
--capacity-report PATH (or '-' to read its exact bytes from stdin). Subsequent
rebuilds use its SHA-verified copy embedded in the small tracked JSON artifact.
All other inputs are tracked summaries or implementation/protocol references.
No runner imports, model calls, simulator calls, or resampling are performed.
"""

import argparse
import hashlib
import json
from pathlib import Path
import sys


ROOT = Path(__file__).resolve().parents[1]
STEM = "www_control_conditions_20261019"
CAPACITY_PATH = "runs/converter_fix_20261001/summary_closed_loop.md"
INPUTS = {
    "main": "docs/reproduce/converter_fix_20261001_summary_closed_loop.json",
    "controls": "docs/reproduce/controls_20261014_summary_controls.json",
    "revision": "docs/reproduce/revision_scenario_v2_20261013_summary_closed_loop_cancelled_moved.json",
    "revision_contract": "contracts/revision_scenario_v2_20261013.json",
    "revision_cluster_code": "scripts/summarise_revision_scenario.py",
    "metric_code": "scripts/summarise_maintenance_diagnostic.py",
    "episode_code": "src/vera/maintenance_episode.py",
    "native_tick_code": "src/vera/ns3/ns3_multiservice_maint.cc",
}
CAPACITY_ARMS = ["R0_reactive", "M_rule", "M_qwen7b_extract", "M_oracle"]
DIAGNOSTIC_ARMS = ["R0_reactive", "M_rule", "C_lead1_qwen7b", "M_qwen7b_extract", "M_oracle"]
LABELS = {
    "R0_reactive": "Reactive", "M_rule": "Rule",
    "C_lead1_qwen7b": "Fixed lead-1", "M_qwen7b_extract": "7B lookahead",
    "M_oracle": "True window",
}


def sha(data):
    return hashlib.sha256(data).hexdigest()


def source(path, data):
    return {"path": path, "sha256": sha(data), "bytes": len(data)}


def capacity_rows(text):
    """Read printed means verbatim; do not derive them from world-level data."""
    lines = text.splitlines()
    heading = lines.index("Satisfaction by (path, remaining Mbps), descriptive:")
    header = next(line for line in lines[heading:] if line.startswith("| path, Mbps |"))
    columns = [v.strip() for v in header.strip("|").split("|")]
    rows = []
    for line in lines[heading:]:
        if not line.startswith("| 3, "):
            continue
        fields = [v.strip() for v in line.strip("|").split("|")]
        values = dict(zip(columns, fields))
        path, capacity = values["path, Mbps"].split(", ")
        rows.append({
            "path": int(path), "remaining_mbps": capacity, "worlds": int(values["n"]),
            "satisfaction_printed": {arm: values[arm] for arm in CAPACITY_ARMS},
        })
    if ([r["remaining_mbps"] for r in rows] != ["1.5", "2.0", "3.0"]
            or any(r["worlds"] != 159 for r in rows)):
        raise ValueError("Unexpected archived capacity groups")
    return rows


def table(report):
    lines = [
        "% Generated by scripts/build_www_control_conditions.py; saved summaries only.",
        r"\begin{table}[t]", r"\centering",
        r"\caption{Conditions and diagnostics from saved post-fix summaries. Panel (a): 159 worlds per capacity. Panel (b): 477 worlds per arm; window satisfaction averages the within-event fraction for each world. Uncertified intervals are counts per 12-tick episode, not realised violations.}",
        r"\label{tab:control-conditions}", r"\footnotesize",
        r"\setlength{\tabcolsep}{4pt}",
        r"\begin{tabular}{@{}lrrrr@{}}", r"\toprule",
        r"\multicolumn{5}{@{}l}{(a) Satisfaction by remaining capacity} \\",
        r"Mbps & Reactive & Rule & 7B & True window \\", r"\midrule",
    ]
    for row in report["capacity"]:
        lines.append(" & ".join([row["remaining_mbps"]]
                                + [row["satisfaction_printed"][a] for a in CAPACITY_ARMS]) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\par\vspace{4pt}",
              r"\begin{tabular}{@{}lrr@{}}", r"\toprule",
              r"\multicolumn{3}{@{}l}{(b) Event-window outcomes and certification} \\",
              r"Arm & Window sat. & Uncertified/ep. \\", r"\midrule"]
    for row in report["diagnostics"]:
        lines.append(f"{row['label']} & {row['window_satisfaction']:.3f} & {row['uncertified_per_episode']:.3f} " + r"\\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    return "\n".join(lines) + "\n"


def markdown(report):
    lines = [
        "# WWW control conditions and metric presentation (2026-10-19)", "",
        "This presentation copies existing summaries. No statistics, intervals, models or packet simulations were rerun.", "",
        "## Capacity conditions", "",
        "Post-conversion-fix values, already rounded to three decimals in the archived report; 159 worlds per capacity. "
        "These descriptive means do not establish significance within a capacity stratum.", "",
        "| Remaining Mbps | Reactive | Rule | 7B lookahead | True window |",
        "|---|---:|---:|---:|---:|",
    ]
    for row in report["capacity"]:
        lines.append("| " + " | ".join([row["remaining_mbps"]]
                                        + [row["satisfaction_printed"][a] for a in CAPACITY_ARMS]) + " |")
    lines += ["", "## Window outcomes and uncertified intervals", "",
              "477 worlds per arm. Window satisfaction is the mean of each world's satisfied fraction during the true event. "
              "Uncertified intervals are mean counts per 12-tick episode. They are not hard-SLA failures.", "",
              "| Arm | Window satisfaction | Uncertified / episode |", "|---|---:|---:|"]
    for row in report["diagnostics"]:
        lines.append(f"| {row['label']} | {row['window_satisfaction']:.3f} | {row['uncertified_per_episode']:.3f} |")
    lines += ["", "## Implementation and sampling units", "",
              "- The revision experiment contains 35 cancelled/moved revision items, 30 notice clusters, and 210 worlds. "
              "Its legacy summary field `providers: 30` counts notice clusters: the summariser substitutes `notice` for `site`.",
              "- Only failure of all base-selection options causes an uncertified hold. A failed maintenance escape can retain "
              "the original target; search failure is not an infeasibility proof.",
              "- The native Tick callback waits for the action file while the simulation clock is paused, then schedules "
              "the next tick one simulated second later. Scores do not include wall-clock decision latency or test real-time deadlines.", "",
              "## Provenance and validation", "",
              "All source paths are repository-relative. The JSON includes SHA-256 hashes, exact archived capacity-report text, "
              "raw selected diagnostic fields and protocol/code references. The saved control and main-summary diagnostic fields "
              "are checked for exact equality for their shared arms. The capacity input is the post-fix report, not the older v2 report.", ""]
    for name, item in report["sources"].items():
        lines.append(f"- {name}: `{item['path']}`, SHA-256 `{item['sha256']}`.")
    lines += ["", "Rebuild with `python3 scripts/build_www_control_conditions.py`; the archived capacity report is embedded "
              "and SHA-verified, so this rebuild needs neither SSH nor ignored historical run directories. "
              "The generated table is `paper_www2027/tables/control_conditions.tex`.", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--capacity-report", help="Archived Markdown path, or '-' for exact stdin bytes")
    args = parser.parse_args()
    output = ROOT / "docs/reproduce" / f"{STEM}.json"
    existing = json.loads(output.read_text()) if output.exists() else None
    if args.capacity_report:
        raw = sys.stdin.buffer.read() if args.capacity_report == "-" else Path(args.capacity_report).read_bytes()
    elif existing:
        raw = existing["sources"]["capacity_report"]["text"].encode("utf-8")
        if sha(raw) != existing["sources"]["capacity_report"]["sha256"]:
            raise ValueError("Embedded capacity report failed SHA verification")
    else:
        raise ValueError("First build requires --capacity-report")
    sources = {"capacity_report": {**source(CAPACITY_PATH, raw), "text": raw.decode("utf-8")}}
    loaded = {}
    for name, path in INPUTS.items():
        data = (ROOT / path).read_bytes()
        sources[name] = source(path, data)
        if existing and sources[name]["sha256"] != existing["sources"][name]["sha256"]:
            raise ValueError(f"Source changed since this presentation was recorded: {path}")
        if path.endswith(".json"):
            loaded[name] = json.loads(data)
    for arm in CAPACITY_ARMS:
        if loaded["main"]["arms"][arm] != loaded["controls"]["arms"][arm]:
            raise ValueError(f"Main/control saved reference fields differ: {arm}")
    if loaded["controls"]["worlds"] != 477 or loaded["revision"]["worlds"] != 210 or loaded["revision"]["providers"] != 30:
        raise ValueError("Unexpected world or cluster counts")
    if "35 informative test items" not in loaded["revision_contract"]["relation"]:
        raise ValueError("Revision contract no longer establishes the item count")
    diagnostics = []
    for arm in DIAGNOSTIC_ARMS:
        stats = loaded["controls"]["arms"][arm]
        diagnostics.append({"arm": arm, "label": LABELS[arm], "worlds": 477,
                            "window_satisfaction": stats["win"], "uncertified_per_episode": stats["unc"],
                            "saved_fields": stats})
    report = {
        "schema": "www.control_conditions/1", "kind": "presentation_of_saved_summaries_only",
        "sources": sources, "capacity": capacity_rows(raw.decode("utf-8")), "diagnostics": diagnostics,
        "revision_units": {"items": 35, "notice_clusters": 30, "worlds": 210,
                           "legacy_cluster_field": "providers", "cluster_unit": "notice"},
        "limitations": ["No new estimates, confidence intervals, resampling, models, or simulation.",
                        "Capacity means retain the original report's three-decimal precision.",
                        "Uncertified and realised violation are different properties; their joint distribution is not inferred.",
                        "Search failure is not an infeasibility proof; simulation scores exclude decision latency."],
    }
    output.write_text(json.dumps(report, indent=2, ensure_ascii=False, allow_nan=False) + "\n")
    (ROOT / "docs/reproduce" / f"{STEM}.md").write_text(markdown(report))
    (ROOT / "paper_www2027/tables/control_conditions.tex").write_text(table(report))
    print("Wrote capacity/diagnostic presentation; archived source and shared-summary checks passed.")


if __name__ == "__main__":
    main()
